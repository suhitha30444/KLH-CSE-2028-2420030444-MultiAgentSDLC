# Phase 6: real Tester — sandboxed, per-criterion execution
# ---------------------------------------------------------------------------
#
# DECISION: the Tester generates its OWN test code via the worker LLM (the
# same "mechanical, high-volume, smaller model" tier the Coder uses per
# PROJECT_BRIEF.md's mixed-model decision), one self-contained script per
# acceptance criterion, which is then genuinely executed in sandbox.py's
# subprocess sandbox. This was the one real architectural gap the roadmap
# didn't spell out explicitly: "check/derive a result per acceptance
# criterion" requires SOMETHING to execute, and nothing upstream (the
# Coder) produces test code today — only implementation code. Generating
# the test per-criterion, right before running it, is what makes "one
# result per criterion" honest rather than a single script's exit code
# fanned out across N criteria.
#
# This also matches the SAME reliability lesson Phase 5 already learned
# with the Planner/Coder/Reviewer: structured JSON output, validated with
# Pydantic-adjacent manual checks below, not the LLM directly executing
# anything or being trusted blind.


def _build_tester_prompt(spec: Spec, code_artifacts: list[CodeArtifact]) -> str:
    """Includes the FULL content of every code artifact (not just
    filenames) — the Tester LLM has to reference real function/class names
    to write a test that actually exercises the code, the same reason
    run_coder()'s prompt includes the full spec rather than a summary.
    """
    criteria_desc = "\n".join(f"  - {c.id}: {c.text}" for c in spec.acceptance_criteria)
    files_desc = "\n\n".join(
        f"--- {a.filename} ---\n{a.content}" for a in code_artifacts
    )
    module_names = ", ".join(a.filename.removesuffix(".py") for a in code_artifacts)

    return f"""You are the Tester agent in a multi-agent SDLC pipeline. You do
NOT judge correctness yourself — you write a small Python test SCRIPT per
acceptance criterion, which will actually be executed in a sandbox. The
exit code decides pass/fail, not your opinion.

Produce a JSON object with EXACTLY one field:

  "tests": a list of objects, ONE PER ACCEPTANCE CRITERION LISTED BELOW
      (same criterion_id values, none missing, none invented), each with:
      "criterion_id" — matching one of the criterion ids below.
      "test_code"    — a COMPLETE, SELF-CONTAINED Python script (no
                        markdown fences) that:
                          - imports what it needs from these modules by
                            name: {module_names}
                          - exercises the code against this ONE criterion
                          - lets an AssertionError (or any uncaught
                            exception) propagate if the criterion is NOT
                            satisfied — do not catch and swallow it
                          - exits normally (falls off the end) if the
                            criterion IS satisfied
                          - uses ONLY the Python standard library, no
                            network access, no reading stdin, no pytest
                            (this is a plain script run directly, not
                            collected by a test runner)

CRITICAL JSON-ESCAPING RULE for "test_code": encode it as an ORDINARY
JSON string, nothing more. A newline in your script must appear as
EXACTLY ONE backslash followed by the letter n (\n) inside the JSON
string — do NOT escape the backslash itself. Do not pre-escape the code
as if you were embedding a Python string literal inside another string.
Two backslashes before an n will produce a script that collapses onto a
single line and fails to even run.

Output ONLY the JSON object — no prose, no markdown code fences.

Acceptance criteria:
{criteria_desc}

Code under test:
{files_desc}
"""


def run_tester_real(
    run_id: str,
    spec: Spec,
    code_artifacts: list[CodeArtifact],
    *,
    mock_response: str | None = None,
) -> list[PerCriterionResult]:
    """
    Phase 6's real Tester. For each acceptance criterion: ask the worker
    LLM for a standalone test script (see _build_tester_prompt), write it
    alongside the Coder's actual code artifacts into a fresh sandbox
    directory (sandbox.run_sandboxed — a NEW temp dir per criterion, so
    one test can't see or be influenced by another), execute it for real,
    and derive passed/failed from the real exit code plus captured
    stdout/stderr — never a guess, never an LLM opinion standing in for
    execution.

    Raises TesterOutputError (not a PerCriterionResult failure) when the
    Tester LLM itself doesn't produce usable test code — invalid JSON, a
    missing 'tests' list, a malformed entry, or a missing criterion_id.
    That's a "the Tester hasn't produced something usable yet" failure,
    same category Phase 4's decision #1 established for Planner/Coder,
    and graph.py's tester_node resamples through test_review_retries
    exactly like a CoderOutputError today.

    `run_id` is accepted but unused for the same forward-compatibility
    reason run_coder() already documents — kept in case Phase 7's report
    or future persistence wants per-run test-artifact filenames.
    """
    if not code_artifacts:
        # Same honest, non-LLM rule run_tester_stub() applies: no code
        # means every criterion fails, and there's nothing to ask the
        # Tester LLM to write a test against.
        return [
            PerCriterionResult(
                criterion_id=c.id,
                passed=False,
                detail="No code artifacts were produced to test.",
            )
            for c in spec.acceptance_criteria
        ]

    prompt = _build_tester_prompt(spec, code_artifacts)
    try:
        raw = call_llm("tester", prompt, mock_response=mock_response)
    except LLMCallError as e:
        raise TesterOutputError(f"Tester call failed: {e}", "") from e

    try:
        payload = json.loads(_strip_code_fence(raw))
    except json.JSONDecodeError as e:
        raise TesterOutputError(f"Tester response was not valid JSON: {e}", raw)

    if not isinstance(payload, dict) or not isinstance(payload.get("tests"), list):
        raise TesterOutputError(
            "Tester response was valid JSON but missing a 'tests' list.", raw
        )

    tests_by_id: dict[str, str] = {}
    try:
        for t in payload["tests"]:
            tests_by_id[t["criterion_id"]] = t["test_code"]
    except (KeyError, TypeError) as e:
        raise TesterOutputError(
            f"Tester's tests were malformed (missing 'criterion_id'/"
            f"'test_code' or not a list of objects): {e}",
            raw,
        )

    expected_ids = {c.id for c in spec.acceptance_criteria}
    missing = expected_ids - tests_by_id.keys()
    if missing:
        raise TesterOutputError(
            f"Tester did not produce a test for every acceptance criterion "
            f"(missing: {sorted(missing)}).",
            raw,
        )

    # Same static syntax pre-check run_coder() now applies to CodeArtifacts
    # — see _python_syntax_error()'s docstring. Deliberately raised as
    # TesterOutputError (the Tester's own bug) rather than a
    # PerCriterionResult failure: a test script that doesn't even parse
    # would otherwise be reported as "the CODE failed this criterion" when
    # the actual defect is in the Tester's generated test, not the Coder's
    # implementation — an important distinction for anyone reading the
    # traceability report and trying to decide what to fix.
    for criterion_id, test_code in tests_by_id.items():
        syntax_error = _python_syntax_error(test_code, f"test_{criterion_id}.py")
        if syntax_error is not None:
            raise TesterOutputError(
                f"Tester's generated test for {criterion_id} is not valid "
                f"Python (caught before executing it in the sandbox): "
                f"{syntax_error}. This is a defect in the Tester's own "
                f"generated test, not necessarily in the code under test.",
                raw,
            )

    code_files = {a.filename: a.content for a in code_artifacts}

    results: list[PerCriterionResult] = []
    for criterion in spec.acceptance_criteria:
        test_filename = f"test_{criterion.id}.py"
        files_for_this_run = {**code_files, test_filename: tests_by_id[criterion.id]}
        outcome = sandbox.run_sandboxed(files_for_this_run, entry_file=test_filename)
        passed = outcome.returncode == 0 and not outcome.timed_out

        if passed:
            detail = "PASS (real sandboxed execution, exit 0)."
            if outcome.stdout.strip():
                detail += f" stdout: {outcome.stdout.strip()[:300]}"
        else:
            reason = (
                outcome.stderr.strip()
                or outcome.stdout.strip()
                or f"nonzero exit code {outcome.returncode}"
            )
            detail = f"FAILED (real sandboxed execution): {reason[:800]}"

        results.append(
            PerCriterionResult(criterion_id=criterion.id, passed=passed, detail=detail)
        )

    return results


def _build_reviewer_prompt(spec: Spec, test_results: list[PerCriterionResult]) -> str:
    """Mirrors _build_prompt() / _build_coder_prompt() above. Only ever sent
    in real mode (Phase 5) — in Phase 4's mock mode, call_llm() ignores it
    entirely, same as every other agent's prompt right now.
    """
    criteria_by_id = {c.id: c.text for c in spec.acceptance_criteria}
    lines = []
    for r in test_results:
        crit_text = criteria_by_id.get(r.criterion_id, "(unknown criterion)")
        verdict = "PASSED" if r.passed else "FAILED"
        lines.append(f"  - {r.criterion_id} ({crit_text}): {verdict} — {r.detail}")
    results_desc = "\n".join(lines) or "  (no test results)"

    return f"""You are the Reviewer agent in a multi-agent SDLC pipeline.

Given the test results below, produce a JSON object with EXACTLY one field:

  "verdicts": a list of objects, one per criterion, each with:
      "criterion_id"  — matching one of the criterion ids below.
      "approved"      — true/false: your judgment on whether this criterion
                         is genuinely satisfied.
      "justification" — a short, specific reason referencing the test result.

Return exactly one verdict for every criterion_id listed below — do not
omit any, and do not invent new ones.

Output ONLY the JSON object — no prose, no markdown code fences.

Test results:
{results_desc}
"""


def run_reviewer(
    run_id: str,
    spec: Spec,
    test_results: list[PerCriterionResult],
    *,
    mock_response: str | None = None,
) -> list[ReviewVerdict]:
    """
    Call the LLM as the Reviewer (mocked for now), parse its JSON response,
    and return a validated list of ReviewVerdicts.

    Raises ReviewerOutputError for invalid JSON, a missing/malformed
    'verdicts' list, a verdict missing a required field, OR a verdict list
    missing an entry for a criterion the Tester reported on.

    Phase 5 update: the default canned mock "reviewer" response now reads
    as prompt-responsive in real mode (see PHASE_5_PROGRESS_AND_DECISIONS.md's
    "Key finding") — with Phase 6's real Tester now supplying real
    execution evidence instead of stub results, a real-mode Reviewer has
    genuine test evidence to approve or reject against for the first time.
    """
    prompt = _build_reviewer_prompt(spec, test_results)
    try:
        raw = call_llm("reviewer", prompt, mock_response=mock_response)
    except LLMCallError as e:
        # Same reasoning as run_planner()/run_coder() above.
        raise ReviewerOutputError(f"Reviewer call failed: {e}", "") from e

    try:
        payload = json.loads(_strip_code_fence(raw))
    except json.JSONDecodeError as e:
        raise ReviewerOutputError(f"Reviewer response was not valid JSON: {e}", raw)

    if not isinstance(payload, dict) or not isinstance(payload.get("verdicts"), list):
        raise ReviewerOutputError(
            "Reviewer response was valid JSON but missing a 'verdicts' list.",
            raw,
        )

    verdicts: list[ReviewVerdict] = []
    try:
        for v in payload["verdicts"]:
            verdicts.append(
                ReviewVerdict(
                    criterion_id=v["criterion_id"],
                    approved=v["approved"],
                    justification=v["justification"],
                )
            )
    except (KeyError, TypeError) as e:
        raise ReviewerOutputError(
            f"Reviewer's verdicts were malformed (missing a required field "
            f"or not a list of objects): {e}",
            raw,
        )
    except ValidationError as e:
        raise ReviewerOutputError(
            f"Reviewer's verdicts failed schema validation: {e}", raw, errors=e.errors()
        )

    tested_ids = {r.criterion_id for r in test_results}
    verdict_ids = {v.criterion_id for v in verdicts}
    missing = tested_ids - verdict_ids
    if missing:
        raise ReviewerOutputError(
            f"Reviewer did not return a verdict for every tested criterion "
            f"(missing: {sorted(missing)}).",
            raw,
        )

    return verdicts
