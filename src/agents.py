def _python_syntax_error(content: str, filename: str = "<generated>") -> str | None:
    """Returns a human-readable SyntaxError message if `content` isn't
    valid Python source, or None if it compiles cleanly. Uses
    `compile(..., "exec")` as a pure STATIC parse check — zero execution,
    no sandbox needed, no risk from the content itself.

    Exists to catch a real failure mode found on a live Groq run (see
    PHASE_6_PROGRESS_AND_DECISIONS.md): a free-tier model can return
    STRUCTURALLY VALID JSON whose string content is still broken Python —
    specifically, double-escaped newlines (the JSON contains a literal
    backslash-backslash-n instead of backslash-n), which collapses an
    entire file onto one physical line. That passes every check that
    existed before this one — valid JSON, has 'filename'/'content',
    matches the Pydantic schema — and previously wasn't caught until the
    Tester's sandbox tried to import/run it, burning a full Tester+Reviewer
    LLM round-trip (and a chunk of the shared retry budget) on code that
    was never going to work. A zero-cost, zero-network compile() check
    catches it instantly instead, with a precise, actionable reason.
    """
    try:
        compile(content, filename, "exec")
    except SyntaxError as e:
        return f"{type(e).__name__}: {e.msg} (line {e.lineno}, col {e.offset})"
    return None


class TesterOutputError(Exception):
    """Phase 6: raised when the real Tester's LLM-generated test scripts
    can't be turned into a runnable set of per-criterion tests — invalid
    JSON, a missing 'tests' list, a test entry missing 'criterion_id'/
    'test_code', or a test missing for one of the Spec's acceptance
    criteria. Same shape as CoderOutputError/ReviewerOutputError, same
    reasoning: graph.py's tester_node catches this and resamples through
    the existing test_review_retries budget rather than crashing the run.

    Deliberately NOT raised for "the generated test ran and the criterion
    failed" — that's real, honest signal (a PerCriterionResult with
    passed=False), not an error. This exception is only for "the Tester
    itself didn't produce something we can execute at all."
    """

    def __init__(self, message: str, raw_response: str, errors: list | None = None):
        super().__init__(message)
        self.raw_response = raw_response
        self.errors = errors or []


def _build_coder_prompt(spec: Spec, previous_error: str | None = None) -> str:
    """The literal text that would be sent to the LLM in real mode (Phase 5).
    Mirrors _build_prompt() above: written now so mock-mode testing
    exercises something realistic, even though nothing calls Groq with it
    yet.

    `previous_error` closes the "paste the bad response back to the LLM"
    gap PlannerOutputError's docstring flagged as a Phase 5 TODO back in
    Phase 2. Without it, every retry re-sent this EXACT prompt, so a model
    that made a systematic mistake (e.g. double-escaping newlines) had no
    way to learn it happened and kept repeating the identical mistake for
    the whole retry budget — the literal failure mode that burned all 5
    attempts on a live ShoppingCart run (4x invalid-JSON, then the same
    double-escaped-newline syntax error on the 5th). When set, this is
    str(exc) from the CoderOutputError the previous attempt raised, and is
    appended as a correction the model is explicitly told to fix.
    """
    criteria_desc = "\n".join(f"  - {c.id}: {c.text}" for c in spec.acceptance_criteria)
    tasks_desc = "\n".join(
        f"  - {t.id}: {t.description} (addresses: {', '.join(t.addresses_criteria) or 'none'})"
        for t in spec.tasks
    ) or "  (none given)"

    prompt = f"""You are the Coder agent in a multi-agent SDLC pipeline.

Given this approved spec, produce a JSON object with EXACTLY one field:

  "artifacts": a list of objects, each with:
      "filename" — a bare filename (no path separators — rejected by the
                    schema if present).
      "content"  — the full file content implementing the task(s) below,
                    as REAL, RUNNABLE Python source.
      "task_id"  — which task (by id, e.g. "T1") this file implements.

CRITICAL JSON-ESCAPING RULE for "content": encode it as an ORDINARY JSON
string, nothing more. A newline in your Python code must appear as
EXACTLY ONE backslash followed by the letter n (\n) inside the JSON
string — do NOT escape the backslash itself. Do not pre-escape the code
as if you were embedding a Python string literal inside another string.
If you find yourself writing two backslashes before an n, that is wrong
and will produce a file that collapses onto a single line and fails to
import.

Prefer ONE consolidated file for a single cohesive class/module, even if
multiple tasks address it, rather than splitting one small piece of
functionality across several separate files.

Output ONLY the JSON object — no prose, no markdown code fences.

Requirement: {spec.requirement}

Acceptance criteria:
{criteria_desc}

Tasks:
{tasks_desc}
"""

    if previous_error:
        prompt += f"""
THIS IS A RETRY. Your previous attempt failed for this exact reason:

{previous_error}

Fix that specific problem before answering again -- do not repeat it. If
it mentions JSON or a syntax error, re-read the CRITICAL JSON-ESCAPING
RULE above: a newline inside "content" must be a single backslash
followed by "n", never two backslashes followed by "n".
"""

    return prompt


def run_coder(
    run_id: str,
    spec: Spec,
    *,
    mock_response: str | None = None,
    previous_error: str | None = None,
) -> list[CodeArtifact]:
    """
    Call the LLM as the Coder (mocked for now), parse its JSON response, and
    return a validated list of CodeArtifacts.

    Raises CoderOutputError — with the raw text attached — for invalid
    JSON, a missing/malformed 'artifacts' list, an artifact missing
    'filename'/'content', or zero artifacts produced (nothing to test is
    treated as a Coder failure, not silently handed to the Tester as an
    empty run).

    `run_id` isn't used yet (Phase 4 doesn't persist CodeArtifacts to disk
    the way Phase 2 persists Specs) — kept in the signature now so it
    doesn't have to change shape later if Phase 6/7 want per-run artifact
    filenames, same reasoning llm_client.py already applies to `prompt`.

    `previous_error` is passed straight through to `_build_coder_prompt()`
    — see its docstring for why this exists. graph.py's coder_node is
    responsible for remembering the last CoderOutputError across retries
    and passing it back in here; run_coder() itself is stateless per call.
    """
    prompt = _build_coder_prompt(spec, previous_error=previous_error)
    try:
        raw = call_llm("coder", prompt, mock_response=mock_response)
    except LLMCallError as e:
        # Same reasoning as run_planner() above: a call-level failure
        # reuses CoderOutputError / test_review_retries rather than
        # crashing the run or inventing a new retry budget.
        raise CoderOutputError(f"Coder call failed: {e}", "") from e

    try:
        payload = json.loads(_strip_code_fence(raw))
    except json.JSONDecodeError as e:
        raise CoderOutputError(f"Coder response was not valid JSON: {e}", raw)

    if not isinstance(payload, dict) or not isinstance(payload.get("artifacts"), list):
        raise CoderOutputError(
            "Coder response was valid JSON but missing an 'artifacts' list.",
            raw,
        )

    raw_artifacts = payload["artifacts"]
    if not raw_artifacts:
        raise CoderOutputError("Coder produced zero artifacts — nothing to test.", raw)

    artifacts: list[CodeArtifact] = []
    try:
        for a in raw_artifacts:
            artifacts.append(
                CodeArtifact(
                    filename=a["filename"],
                    content=a["content"],
                    task_id=a.get("task_id"),
                )
            )
    except (KeyError, TypeError) as e:
        raise CoderOutputError(
            f"Coder's artifacts were malformed (missing 'filename'/'content' "
            f"or not a list of objects): {e}",
            raw,
        )
    except ValidationError as e:
        raise CoderOutputError(
            f"Coder's artifacts failed schema validation: {e}", raw, errors=e.errors()
        )

    # Catch broken-but-technically-valid-JSON content (e.g. double-escaped
    # newlines) HERE, before it ever reaches the Tester's sandbox — see
    # _python_syntax_error()'s docstring for the real run that surfaced
    # this. Cheaper (no LLM calls spent generating tests for code that
    # can't even be imported) and more honest (the error names the exact
    # syntax problem instead of every criterion failing with an opaque
    # import traceback).
    for artifact in artifacts:
        syntax_error = _python_syntax_error(artifact.content, artifact.filename)
        if syntax_error is not None:
            raise CoderOutputError(
                f"Coder's artifact {artifact.filename!r} is not valid Python "
                f"(caught before reaching the sandbox): {syntax_error}. A common "
                f"cause: the model double-escaped newlines in its JSON string "
                f"(wrote two backslashes before 'n' instead of one), which "
                f"collapses the whole file onto a single line.",
                raw,
            )

    return artifacts


def run_tester_stub(
    spec: Spec,
    code_artifacts: list[CodeArtifact],
    *,
    force_fail_criteria: list[str] | None = None,
) -> list[PerCriterionResult]:
    """
    Phase 4's STUB Tester. Kept in Phase 6 ONLY as the deliberate-override
    testing/demo hook (`force_fail_criteria`) — see this module's
    run_tester_real() below for the real sandboxed execution that
    production runs actually use. graph.py's tester_node calls THIS
    function only when the graph state explicitly carries
    force_tester_fail_criteria/force_tester_fail_attempts (test/demo
    runs), and calls run_tester_real() otherwise. A real Tester can't
    honestly "force" a criterion to fail regardless of whether the code
    actually satisfies it — that would contradict the entire point of
    Phase 6 — so the override intentionally keeps living on the
    honest-about-being-fake stub, never on the real path.

    No subprocess, no sandbox, no actually running the generated code.
    Rule-based logic, in order:
      1. If no code_artifacts were produced at all, every criterion fails
         with that as the explicit reason. This is the one part of this
         function that's a REAL rule, not a stub — "no code exists" is
         something we can honestly determine without executing anything.
      2. If a criterion's id is in `force_fail_criteria`, it fails with a
         detail that says so explicitly. This is a test/demo hook only.
      3. Otherwise, the criterion is assumed to pass. This is the actual
         "stub" part — there's no way to honestly know without execution.

    Every PerCriterionResult.detail is prefixed "[stub]" except the
    no-code-produced case, so nothing downstream (the Reviewer's prompt,
    Phase 7's traceability report) can mistake a stub result for a real
    one.
    """
    force_fail = set(force_fail_criteria or [])
    results: list[PerCriterionResult] = []

    for criterion in spec.acceptance_criteria:
        if not code_artifacts:
            results.append(
                PerCriterionResult(
                    criterion_id=criterion.id,
                    passed=False,
                    detail="No code artifacts were produced to test.",
                )
            )
        elif criterion.id in force_fail:
            results.append(
                PerCriterionResult(
                    criterion_id=criterion.id,
                    passed=False,
                    detail=(
                        f"[stub] forced failure for {criterion.id} "
                        f"(test/demo hook only — production runs use "
                        f"run_tester_real(), Phase 6)."
                    ),
                )
            )
        else:
            results.append(
                PerCriterionResult(
                    criterion_id=criterion.id,
                    passed=True,
                    detail="[stub] assumed pass — test/demo hook only, not real execution.",
                )
            )

    return results


