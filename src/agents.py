_CODE_FENCE_RE = re.compile(r"^```(?:json)?\s*\n?(.*?)\n?```\s*$", re.DOTALL)


def _strip_code_fence(raw: str) -> str:
    """Every agent prompt already says "no markdown code fences", but that's
    an instruction, not an enforcement — and as of this pass, coder/tester
    no longer get Groq's response_format=json_object structural nudge
    either (see llm_client.py's _ROLES_WITHOUT_JSON_MODE for why: it was
    causing opaque, undebuggable rejections on large code payloads). This
    is the cheap defensive counterweight: if a response is wrapped in a
    ```json ... ``` or ``` ... ``` fence despite the instruction, strip it
    before attempting json.loads() rather than failing on a fence that a
    human would recognize as "obviously JSON, just decorated." A no-op on
    any response that isn't fenced (including every existing mock
    fixture), so this changes nothing about current passing behavior.
    """
    stripped = raw.strip()
    match = _CODE_FENCE_RE.match(stripped)
    return match.group(1).strip() if match else stripped


class PlannerOutputError(Exception):
    """Raised when the Planner's LLM output can't be turned into a valid
    Spec. Carries the raw response text and (when available) the structured
    Pydantic errors, so whatever calls run_planner has enough to show a
    human (Phase 3's approval gate) or eventually feed back to the LLM as a
    "here's what was wrong, try again" prompt (Phase 5).

    Phase 2 itself does NOT retry — RetryCounters.spec_approval_retries is a
    Phase 3 concern. Phase 2's job is only to prove this failure is caught
    cleanly and says something specific, not "something went wrong."
    """

    def __init__(self, message: str, raw_response: str, errors: list | None = None):
        super().__init__(message)
        self.raw_response = raw_response
        self.errors = errors or []


def _build_prompt(requirement: str) -> str:
    """The literal text that would be sent to the LLM in real mode (Phase 5).
    Written now, even though nothing calls Groq with it yet, so mock-mode
    testing exercises something realistic rather than an empty string.

    Note the explicit instruction NOT to include an "id" on each acceptance
    criterion: AcceptanceCriterion.id is generated by our own code after
    parsing (AC1, AC2, ... in list order) — see PHASE_0_1_PROGRESS_AND_DECISIONS.md,
    "Open questions from Phase 1 — all resolved", item 1. Letting the LLM
    invent ids risks duplicates or inconsistent formats across runs.

    Also note tasks reference criteria by 0-based INDEX into
    acceptance_criteria, not by id and not by text. The LLM can't know the
    id we're about to assign (we haven't assigned it yet when the LLM
    responds), and referencing by text is fragile (a one-character mismatch
    breaks the link). Index into the list it just produced is the only
    stable thing available at response time — run_planner() below resolves
    each index to the real generated id right after parsing.
    """
    return f"""You are the Planner agent in a multi-agent SDLC pipeline.

Given this plain-English software requirement, produce a JSON object with
EXACTLY these fields and nothing else:

  "requirement": the requirement, copied verbatim.

  "acceptance_criteria": a list of objects, each with ONLY a "text" field —
      one independently-checkable condition the final code must satisfy.
      Do NOT include an "id" field on these; ids are assigned by our code,
      not by you.

  "tasks": a list of objects, each with:
      "id"                 — a short stable string like "T1", "T2", ...
      "description"        — what this task implements.
      "addresses_criteria" — a list of 0-based INTEGER INDICES into the
                              acceptance_criteria list above (NOT ids, NOT
                              text) naming which criteria this task
                              addresses. Use [] for setup/scaffolding tasks
                              that don't map to any single criterion.

Output ONLY the JSON object — no prose, no markdown code fences.

Requirement: {requirement}
"""


def run_planner(
    run_id: str,
    requirement: str,
    *,
    mock_response: str | None = None,
) -> Spec:
    """
    Call the LLM as the Planner (mocked for now), parse its JSON response,
    and return a validated Spec.

    Raises PlannerOutputError — with the raw text attached — the moment
    anything about the response can't be trusted: invalid JSON, a
    criterion/task missing a required field, a task's addresses_criteria
    pointing at an index that doesn't exist, or the assembled Spec itself
    failing Pydantic validation (e.g. zero acceptance criteria). Failing
    loudly and specifically here is the entire point of Phase 1's schema
    work — see EVALUATION_AND_ROADMAP.md's Phase 2 "done when".
    """
    prompt = _build_prompt(requirement)
    try:
        raw = call_llm("planner", prompt, mock_response=mock_response)
    except LLMCallError as e:
        # A call-level failure (Groq rejected the request outright, e.g.
        # json_validate_failed) is the same category of "hasn't produced
        # something usable yet" as a content-level failure below — see
        # PHASE_4_PROGRESS_AND_DECISIONS.md decision #1. Reusing
        # PlannerOutputError here, not a new exception type, is what lets
        # the existing spec_approval_retries loop resample through it.
        raise PlannerOutputError(f"Planner call failed: {e}", "") from e

    try:
        payload = json.loads(_strip_code_fence(raw))
    except json.JSONDecodeError as e:
        raise PlannerOutputError(f"Planner response was not valid JSON: {e}", raw)

    if not isinstance(payload, dict):
        raise PlannerOutputError(
            f"Planner response was valid JSON but not a JSON object "
            f"(got {type(payload).__name__}).",
            raw,
        )

    # --- Acceptance criteria: assign ids ourselves, AC1, AC2, ... in order ---
    raw_criteria = payload.get("acceptance_criteria", [])
    try:
        criteria = [
            AcceptanceCriterion(id=f"AC{i + 1}", text=c["text"])
            for i, c in enumerate(raw_criteria)
        ]
    except (KeyError, TypeError) as e:
        raise PlannerOutputError(
            f"Planner's acceptance_criteria were malformed (missing 'text' "
            f"or not a list of objects): {e}",
            raw,
        )
    except ValidationError as e:
        raise PlannerOutputError(
            f"Planner's acceptance_criteria failed schema validation: {e}",
            raw,
            errors=e.errors(),
        )

    # --- Tasks: resolve each addresses_criteria index to the real id ---
    raw_tasks = payload.get("tasks", [])
    tasks: list[TaskItem] = []
    try:
        for t in raw_tasks:
            resolved_ids = []
            for idx in t.get("addresses_criteria", []):
                if not isinstance(idx, int) or isinstance(idx, bool) or not (0 <= idx < len(criteria)):
                    raise PlannerOutputError(
                        f"Task {t.get('id')!r} references criterion index "
                        f"{idx!r}, which is out of range for the "
                        f"{len(criteria)} acceptance criteria the Planner "
                        f"actually produced.",
                        raw,
                    )
                resolved_ids.append(criteria[idx].id)
            tasks.append(
                TaskItem(
                    id=t["id"],
                    description=t["description"],
                    addresses_criteria=resolved_ids,
                )
            )
    except (KeyError, TypeError) as e:
        raise PlannerOutputError(
            f"Planner's tasks were malformed (missing 'id'/'description' or "
            f"not a list of objects): {e}",
            raw,
        )
    except ValidationError as e:
        raise PlannerOutputError(
            f"Planner's tasks failed schema validation: {e}", raw, errors=e.errors()
        )

    try:
        spec = Spec(
            run_id=run_id,
            requirement=payload.get("requirement", requirement),
            acceptance_criteria=criteria,
            tasks=tasks,
        )
    except ValidationError as e:
        raise PlannerOutputError(
            f"Planner output built individually-valid pieces, but the "
            f"assembled Spec failed validation: {e}",
            raw,
            errors=e.errors(),
        )

    return spec


